"""Flattens analysis/results.json and analysis/agreement.json into LaTeX macros (paper/numbers.tex).
In the paper, \\num{key} prints a value; a proportion dict {k,n,p,lo,hi} gives keys key.k, key.n, key.kn ("k/n"),
key.pct, key.ci ("[lo, hi]" in percent). Every number of the paper goes through this file."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}


def fmt_p(p):
    if p < 0.001:
        return "< 0.001"
    return f"{p:.3f}"


def walk(prefix, v):
    if isinstance(v, dict) and {"k", "n", "lo", "hi"} <= set(v):
        out[prefix + ".k"] = str(v["k"]); out[prefix + ".n"] = str(v["n"]); out[prefix + ".kn"] = f"{v['k']}/{v['n']}"
        out[prefix + ".pct"] = (f"{100 * v['k'] / v['n']:.0f}\\,\\%" if v["n"] else "n/a")
        out[prefix + ".ci"] = f"[{100 * v['lo']:.0f}, {100 * v['hi']:.0f}]\\,\\%"
        return
    if isinstance(v, dict):
        for k, x in v.items():
            walk(f"{prefix}.{k}" if prefix else str(k), x)
        return
    if isinstance(v, (list, tuple)) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        out[prefix] = f"[{v[0]:.2f}, {v[1]:.2f}]"
        return
    if isinstance(v, float):
        out[prefix] = f"{v:.2f}"
        if "p_raw" in prefix or "holm" in prefix or "fisher_p" in prefix:
            out[prefix] = fmt_p(v)
        return
    out[prefix] = str(v)


walk("", json.load(open(f"{ROOT}/analysis/results.json")))
walk("agr", json.load(open(f"{ROOT}/analysis/agreement.json")))
for pre, fn in (("cx", "crossfamily.json"), ("mon", "monitor.json")):
    if os.path.exists(f"{ROOT}/analysis/{fn}"):
        walk(pre, json.load(open(f"{ROOT}/analysis/{fn}")))
# factorial cells from the original study's derived tables (checked against raw folders by verify/recount_raw.py)
import csv
W = os.path.expanduser("~/work/swarm-alignment-data")
from xstats_path import X  # noqa: E402
for tag, d in (("frozen", "derive-v6"), ("ext", "derive-v6x")):
    pool = {}
    for r in csv.DictReader(open(f"{W}/{d}/factorial/factorial_cells.csv")):
        k, n = int(r["bypass"]), int(r["n"])
        out[f"fact.{tag}.{r['package']}.{r['task']}.{r['cell']}"] = f"{k}/{n}"
        a = pool.setdefault(r["cell"], [0, 0]); a[0] += k; a[1] += n
    for c, (k, n) in pool.items():
        lo, hi = X.clopper_pearson(k, n)
        out[f"fact.{tag}.pooled.{c}.kn"] = f"{k}/{n}"
        out[f"fact.{tag}.pooled.{c}.pct"] = f"{100 * k / n:.0f}\\,\\%"
        out[f"fact.{tag}.pooled.{c}.ci"] = f"[{100 * lo:.0f}, {100 * hi:.0f}]\\,\\%"
reg = {r["key"]: r["value"] for r in csv.DictReader(open(os.path.expanduser(
    "~/Desktop/Code/Projets/hackathon-swarm-alignment/banc/analyse/registre.csv")))}
for k in ("fact.HF1.holm_p", "fact.HF2.holm_p", "fact.HF1.effect_mean", "fact.HF2.effect_mean"):
    v = float(reg[k])
    out["orig." + k] = fmt_p(v) if "holm" in k else f"{v:.2f}"
with open(f"{ROOT}/paper/numbers.tex", "w") as f:
    f.write("% generated by analysis/make_numbers.py; do not edit\n")
    for k, v in sorted(out.items()):
        safe = v.replace("%", "\\%") if "\\%" not in v else v
        safe = safe.replace("_", "\\_") if "\\" not in safe else safe
        f.write(f"\\expandafter\\def\\csname num@{k}\\endcsname{{{safe}}}\n")
print(f"{len(out)} macros written to paper/numbers.tex")
