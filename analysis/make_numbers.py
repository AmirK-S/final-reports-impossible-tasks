"""Flattens analysis/results.json and analysis/agreement.json into LaTeX macros (paper/numbers.tex).
In the paper, \\num{key} prints a value; a proportion dict {k,n,p,lo,hi} gives keys key.k, key.n, key.kn ("k/n"),
key.pct, key.ci ("[lo, hi]" in percent). Every number of the paper goes through this file."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}


def fmt_p(p):
    if p < 0.001:
        return "< 0.001"
    return f"{p:.3f}"


def walk(prefix, v):
    if isinstance(v, dict) and {"k", "n", "lo", "hi"} <= set(v):
        out[prefix + ".k"] = str(v["k"]); out[prefix + ".n"] = str(v["n"]); out[prefix + ".kn"] = f"{v['k']}/{v['n']}"
        out[prefix + ".pct"] = (f"{100 * v['k'] / v['n']:.0f}\\,\\%" if v["n"] else "n/a")
        out[prefix + ".ci"] = f"[{100 * v['lo']:.0f}, {100 * v['hi']:.0f}]\\,\\%"
        return
    if isinstance(v, dict):
        for k, x in v.items():
            walk(f"{prefix}.{k}" if prefix else str(k), x)
        return
    if isinstance(v, (list, tuple)) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        out[prefix] = f"[{v[0]:.2f}, {v[1]:.2f}]"
        return
    if isinstance(v, float):
        out[prefix] = f"{v:.2f}"
        if "p_raw" in prefix or "holm" in prefix or "fisher_p" in prefix:
            out[prefix] = fmt_p(v)
        return
    out[prefix] = str(v)


walk("", json.load(open(f"{ROOT}/analysis/results.json")))
walk("agr", json.load(open(f"{ROOT}/analysis/agreement.json")))
with open(f"{ROOT}/paper/numbers.tex", "w") as f:
    f.write("% generated by analysis/make_numbers.py; do not edit\n")
    for k, v in sorted(out.items()):
        safe = v.replace("%", "\\%") if "\\%" not in v else v
        safe = safe.replace("_", "\\_") if "\\" not in safe else safe
        f.write(f"\\expandafter\\def\\csname num@{k}\\endcsname{{{safe}}}\n")
print(f"{len(out)} macros written to paper/numbers.tex")
